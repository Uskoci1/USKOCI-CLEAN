import assert from 'node:assert/strict';
import {createControlPrivateClient,CONTROL_PRIVATE_CLIENT_MAX_BYTES} from './runtime/private-client.mjs';
const id='11111111-1111-4111-8111-111111111111',id2='22222222-2222-4222-8222-222222222222';
let calls=[];
const fetchImpl=async(url,init)=>{calls.push({url,init});return new Response(JSON.stringify({ok:true}),{status:200,headers:{'content-type':'application/json'}})};
const c=createControlPrivateClient({origin:'https://control.example',fetchImpl});
await c.session();await c.overview();await c.search('Milos',99);await c.user(id);await c.task(id);await c.agreement(id);await c.application(id);await c.notification(id);await c.ai(id);await c.matching(id,id2);
assert.ok(calls.every(x=>x.init.method==='GET'));
assert.ok(calls.every(x=>x.init.credentials==='same-origin'));
assert.ok(calls.every(x=>x.init.cache==='no-store'));
assert.ok(calls.every(x=>!('authorization' in x.init.headers)));
assert.match(calls.find(x=>x.url.includes('/search?')).url,/limit=20/);
assert.throws(()=>c.search('a'));
assert.throws(()=>c.search('owner@example.invalid'));
assert.throws(()=>c.search('+381641234567'));
assert.throws(()=>c.user('bad'));
assert.throws(()=>createControlPrivateClient({origin:'http://control.example',fetchImpl}),/HTTPS_REQUIRED/);
const huge=createControlPrivateClient({origin:'https://control.example',fetchImpl:async()=>new Response('x'.repeat(CONTROL_PRIVATE_CLIENT_MAX_BYTES+1),{status:200})});
await assert.rejects(()=>huge.overview(),/TOO_LARGE/);
