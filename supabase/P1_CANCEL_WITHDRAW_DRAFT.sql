-- P1: authoritative Need cancellation and Response withdrawal.
--
-- This migration also repairs two regressions exposed by the lifecycle guard:
-- internal deadline expiry and Agreement cancellation must set the lifecycle
-- token before changing needs.status. Finally, rpc_submit_response now stores
-- durable command results so a network retry cannot create a phantom version.

create table if not exists private.response_submit_commands (
  worker_account_id uuid not null,
  client_request_id text not null
    check (char_length(btrim(client_request_id)) between 8 and 200),
  request_hash text not null check (char_length(request_hash) = 64),
  response_id uuid not null,
  response_version integer not null check (response_version >= 1),
  result jsonb not null,
  created_at timestamptz not null default statement_timestamp(),
  primary key (worker_account_id, client_request_id),
  foreign key (response_id, response_version)
    references public.marketplace_response_versions(response_id, version)
    on delete cascade
);

