create or replace function public.rpc_withdraw_response(
  p_response_id uuid,
  p_need_revision integer,
  p_response_version integer,
  p_client_request_id text,
  p_reason text default null
) returns jsonb language plpgsql security definer set search_path to 'pg_catalog' as $$
declare
  u uuid := auth.uid();
  v_need_id uuid;
  n public.needs;
  r public.marketplace_responses;
  v_command private.response_withdraw_commands;
  v_request_hash text;
  v_result jsonb;
  old_status text;
begin
  if u is null then raise exception using errcode='42501', message='AUTH_REQUIRED'; end if;
  if p_client_request_id is null
     or char_length(btrim(p_client_request_id)) not between 8 and 200 then
    raise exception using errcode='22023', message='INVALID_CLIENT_REQUEST_ID';
  end if;

  v_request_hash := encode(sha256(convert_to(jsonb_build_object(
    'responseId', p_response_id,
    'needRevision', p_need_revision,
    'responseVersion', p_response_version,
    'reason', btrim(coalesce(p_reason, ''))
  )::text, 'UTF8')), 'hex');

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(u::text || ':' || p_client_request_id, 7242)
  );

  select * into v_command
    from private.response_withdraw_commands c
   where c.worker_account_id = u
     and c.client_request_id = p_client_request_id;
  if found then
    if v_command.request_hash <> v_request_hash then
      raise exception using errcode='22023', message='IDEMPOTENCY_KEY_REUSED';
    end if;
    return v_command.result || jsonb_build_object('idempotentReplay', true);
  end if;

  -- Discover the parent without locking, then take locks in canonical order:
  -- Need -> Response. Selection and submission use the same order.
  select x.need_id into v_need_id
    from public.marketplace_responses x
   where x.id = p_response_id;
  if not found then raise exception using errcode='P0002', message='RESPONSE_NOT_FOUND'; end if;

  select * into n from public.needs where id = v_need_id for update;
  if not found then raise exception using errcode='P0002', message='NEED_NOT_FOUND'; end if;

  select * into r from public.marketplace_responses x
   where x.id = p_response_id for update;
  if not found then raise exception using errcode='P0002', message='RESPONSE_NOT_FOUND'; end if;
  if r.need_id <> n.id then
    raise exception using errcode='P0001', message='RESPONSE_NEED_MISMATCH';
  end if;
  if r.worker_account_id <> u then
    raise exception using errcode='42501', message='FORBIDDEN';
  end if;
  if not exists (
    select 1 from public.app_profiles p
     where p.id = r.worker_profile_id
       and p.account_id = u
       and p.kind = 'WORKER'
  ) then
    raise exception using errcode='42501', message='PROFILE_NOT_OWNED_BY_ACCOUNT';
  end if;

  if r.status = 'WITHDRAWN' then
    return jsonb_build_object(
      'responseId', r.id,
      'needId', n.id,
      'needRevision', n.revision,
      'submittedNeedRevision', r.submitted_against_need_revision,
      'version', r.current_version,
      'status', r.status,
      'withdrawnAt', r.withdrawn_at,
      'idempotentReplay', true,
      'authoritative', true
    );
  end if;

  if r.current_version is distinct from p_response_version then
    raise exception using errcode='P0001', message='STALE_REVIEW_REQUIRED';
  end if;

  if not exists (
    select 1
      from public.marketplace_response_versions v
     where v.response_id = r.id
       and v.version = r.current_version
       and v.need_revision = r.submitted_against_need_revision
  ) then
    raise exception using errcode='P0002', message='RESPONSE_VERSION_NOT_FOUND';
  end if;

  -- C12.12: every withdrawal decision binds the latest Need revision reviewed
  -- by the Worker. A live Application must also have been submitted against it;
  -- a STALE Application deliberately retains its older immutable binding.
  if n.revision is distinct from p_need_revision
     or (r.status <> 'STALE'
         and r.submitted_against_need_revision is distinct from p_need_revision) then
    raise exception using errcode='P0001', message='STALE_REVIEW_REQUIRED';
  end if;

  if r.status = 'SELECTED'
     or exists (
       select 1 from public.agreements a
        where a.selected_response_id = r.id
          and a.status in ('CONFIRMED','SUPERSEDED','COMPLETED')
     ) then
    raise exception using errcode='P0001', message='RESPONSE_ALREADY_SELECTED';
  end if;

  if r.status not in ('DRAFT','SUBMITTED','DELIVERED','VIEWED','SHORTLISTED','STALE') then
    raise exception using errcode='22023', message='RESPONSE_NOT_WITHDRAWABLE';
  end if;

  old_status := r.status;

  update public.notification_deliveries d
     set state = 'EXPIRED'
    from public.user_activity_events e
   where d.event_id = e.id
     and e.entity_type = 'RESPONSE'
     and e.entity_id = r.id
     and d.state in ('CREATED','QUEUED','FAILED_RETRYABLE');

  update public.marketplace_responses
     set status = 'WITHDRAWN',
         withdrawn_at = statement_timestamp(),
         selected_at = null
   where id = r.id
   returning * into r;

  -- A DRAFT was never visible to the requester, so withdrawing it emits no
  -- cross-party event. Submitted history remains visible and versioned.
  if old_status <> 'DRAFT' then
    perform private.emit_event(
      n.requester_account_id,
      'REQUESTER',
      'RESPONSE_WITHDRAWN',
      'RESPONSE',
      r.id,
      r.current_version,
      'Prijava je povucena',
      'Uskocer je povukao prijavu za Vasu Potrebu.',
      'response-withdrawn:' || r.id::text || ':' || r.current_version::text,
      'NORMAL',
      jsonb_build_object('needId', n.id, 'needRevision', n.revision),
      null
    );
  end if;

  -- Withdrawal can reopen capacity. Wake dispatch only while the Need can still
  -- accept a replacement; an elapsed deadline must never schedule new work.
  if n.status in ('PUBLISHED','SELECTION')
     and (n.response_deadline is null
          or n.response_deadline > statement_timestamp())
     and public.fn_need_covered_slots(n.id) < n.required_slots then
    perform private.enqueue_dispatch(n.id, statement_timestamp());
  end if;

  perform private.audit_marketplace(
    u,
    'RESPONSE_WITHDRAWN',
    'RESPONSE',
    r.id,
    r.current_version,
    jsonb_build_object(
      'needId', n.id,
      'needRevision', n.revision,
      'submittedNeedRevision', r.submitted_against_need_revision,
      'clientRequestId', p_client_request_id,
      'reason', left(btrim(coalesce(p_reason, '')), 300)
    )
  );

  v_result := jsonb_build_object(
    'responseId', r.id,
    'needId', n.id,
    'needRevision', n.revision,
    'submittedNeedRevision', r.submitted_against_need_revision,
    'version', r.current_version,
    'status', r.status,
    'withdrawnAt', r.withdrawn_at,
    'idempotentReplay', false,
    'authoritative', true
  );

  insert into private.response_withdraw_commands (
    worker_account_id, client_request_id, request_hash,
    response_id, response_version, result
  ) values (
    u, p_client_request_id, v_request_hash,
    r.id, r.current_version, v_result
  );

  return v_result;
end;
$$;

