-- Need revision/cancellation events are part of the response lifecycle from a
-- worker's perspective and must honor responses_enabled, not account_enabled.
create or replace function private.category_of_event(p_event_type text)
returns text language sql immutable set search_path to 'pg_catalog' as $$
  select case
    when p_event_type = 'OPPORTUNITY_AVAILABLE' then 'opportunities'
    when p_event_type like 'RESPONSE\_%'
      or p_event_type in ('NEED_REVISED','NEED_CANCELLED') then 'responses'
    when p_event_type like 'AGREEMENT\_%'
      or p_event_type in ('MESSAGE_RECEIVED','PRIVATE_ACCESS_GRANTED','REVIEW_RECEIVED') then 'dogovor'
    when p_event_type in ('EXECUTION_STATE_CHANGED','COMPLETION_REQUIRED') then 'execution'
    when p_event_type = 'RECOVERY_OPENED' then 'recovery'
    else 'account'
  end;
$$;

revoke all on function private.category_of_event(text)
  from public, anon, authenticated;

-- Preserve Claude's ownership/revision guard and close its remaining terminal
-- mutation hole: CANCELLED/EXPIRED/COMPLETED/ARCHIVED truth is immutable.
create or replace function private.guard_need_write()
returns trigger language plpgsql security definer set search_path to 'pg_catalog' as $$
declare
  token text := current_setting('uskoci.need_lifecycle', true);
  material boolean;
begin
  if not exists (
    select 1 from public.app_profiles p
     where p.id = new.requester_profile_id
       and p.account_id = new.requester_account_id
       and p.kind = 'REQUESTER'
  ) then
    raise exception using errcode='42501', message='PROFILE_NOT_OWNED_BY_ACCOUNT';
  end if;

  if tg_op = 'INSERT' then
    if new.status <> 'DRAFT'
       and not (new.status = 'PUBLISHED' and token = 'PUBLISH') then
      raise exception using errcode='22023', message='NEED_MUST_START_AS_DRAFT';
    end if;
    return new;
  end if;

  -- Terminal domain truth is immutable. The only tolerated housekeeping change
  -- is urgent=true -> false (plus the normal updated_at trigger), so expiry of
  -- an old urgency projection can never wedge the marketplace cron.
  if old.status in ('COMPLETED','CANCELLED','EXPIRED','ARCHIVED')
     and (
       (to_jsonb(new) - array['urgent','updated_at'])
         is distinct from
       (to_jsonb(old) - array['urgent','updated_at'])
       or (not coalesce(old.urgent, false) and coalesce(new.urgent, false))
     ) then
    raise exception using errcode='22023', message='NEED_TERMINAL_IMMUTABLE';
  end if;

  if new.requester_account_id <> old.requester_account_id then
    raise exception using errcode='42501', message='NEED_OWNER_IMMUTABLE';
  end if;

  if new.status is distinct from old.status then
    if not (
         (token = 'PUBLISH'
          and old.status = 'DRAFT' and new.status = 'PUBLISHED')
      or (token = 'SELECT'
          and old.status in ('PUBLISHED','SELECTION')
          and new.status in ('SELECTION','ACTIVE'))
      or (token = 'CANCEL_NEED'
          and old.status in ('DRAFT','PUBLISHED','SELECTION')
          and new.status = 'CANCELLED')
      or (token = 'CANCEL_AGREEMENT'
          and old.status in ('ACTIVE','SELECTION')
          and new.status = 'SELECTION')
      or (token = 'EXPIRE'
          and old.status in ('PUBLISHED','SELECTION')
          and new.status = 'EXPIRED')
    ) then
      raise exception using errcode='22023', message='NEED_STATUS_TRANSITION_REQUIRES_RPC';
    end if;
  end if;

  material :=
       new.title is distinct from old.title
    or new.description is distinct from old.description
    or new.category is distinct from old.category
    or new.required_slots is distinct from old.required_slots
    or new.mode is distinct from old.mode
    or new.requester_price_rsd is distinct from old.requester_price_rsd
    or new.required_skills is distinct from old.required_skills
    or new.required_tools is distinct from old.required_tools
    or new.required_vehicles is distinct from old.required_vehicles
    or new.required_licenses is distinct from old.required_licenses
    or new.minimum_experience_years is distinct from old.minimum_experience_years
    or new.verified_identity_required is distinct from old.verified_identity_required
    or new.schedule_kind is distinct from old.schedule_kind
    or new.starts_at is distinct from old.starts_at
    or new.ends_at is distinct from old.ends_at
    or new.execution_location_mode is distinct from old.execution_location_mode
    or new.approximate_lat is distinct from old.approximate_lat
    or new.approximate_lng is distinct from old.approximate_lng;

  if material then
    if old.status in ('PUBLISHED','SELECTION') then
      new.revision := old.revision + 1;
    end if;
  elsif new.revision is distinct from old.revision then
    raise exception using errcode='22023', message='REVISION_BUMP_WITHOUT_MATERIAL_CHANGE';
  end if;

  return new;
end;
$$;

revoke all on function private.guard_need_write()
  from public, anon, authenticated;

-- Repair cron deadline expiry after needs_guard_write made status transitions
-- token-gated. The rest of the previously proven lifecycle remains unchanged.
create or replace function private.expire_lifecycle(
  p_at timestamptz default statement_timestamp()
) returns jsonb language plpgsql security definer set search_path to 'pg_catalog' as $$
declare
  d integer := 0;
  rr integer := 0;
  av integer := 0;
  ur integer := 0;
  ne integer := 0;
  re integer := 0;
  nd integer := 0;
  dq integer := 0;
  changed integer := 0;
begin
  perform set_config('uskoci.need_lifecycle', 'EXPIRE', true);

  with expired_needs as (
    update public.needs x
       set status = 'EXPIRED', urgent = false
     where x.status in ('PUBLISHED','SELECTION')
       and x.response_deadline is not null
       and x.response_deadline <= p_at
       and not exists (
         select 1 from public.need_selections s
          where s.need_id = x.id and s.status = 'SELECTED'
    )
    returning x.id, x.revision
  ), expired_responses as (
    update public.marketplace_responses r
       set status = 'EXPIRED', selected_at = null
      from expired_needs i
     where r.need_id = i.id
       and r.status in ('DRAFT','SUBMITTED','DELIVERED','VIEWED','SHORTLISTED','STALE')
    returning r.id
  ), expired_notifications as (
    update public.notification_deliveries d
       set state = 'EXPIRED'
      from public.user_activity_events e
     where d.event_id = e.id
       and d.state in ('CREATED','QUEUED','FAILED_RETRYABLE')
       and (
         (e.entity_type = 'NEED' and exists (
           select 1 from expired_needs i where i.id = e.entity_id
         ))
         or (e.entity_type = 'RESPONSE' and exists (
           select 1
             from public.marketplace_responses r
             join expired_needs i on i.id = r.need_id
            where r.id = e.entity_id
         ))
       )
    returning d.id
  ), stopped_rounds as (
    update public.dispatch_rounds r
       set status = 'STOPPED', stop_reason = 'NEED_EXPIRED'
      from expired_needs i
     where r.need_id = i.id and r.status in ('PLANNED','SENT')
    returning r.need_id
  ), expired_opportunities as (
    update public.opportunity_deliveries o set status = 'EXPIRED'
      from expired_needs i
     where o.need_id = i.id and o.status in ('READY','SEEN')
    returning o.need_id
  ), dequeued as (
    delete from private.dispatch_schedule s
     using expired_needs i where s.need_id = i.id
    returning s.need_id
  )
  select
    (select count(*)::integer from expired_needs),
    (select count(*)::integer from expired_responses),
    (select count(*)::integer from expired_notifications),
    (select count(*)::integer from stopped_rounds),
    (select count(*)::integer from expired_opportunities),
    (select count(*)::integer from dequeued)
  into ne, re, nd, rr, d, dq;

  update public.opportunity_deliveries
     set status = 'EXPIRED'
   where status in ('READY','SEEN')
     and expires_at is not null and expires_at <= p_at;
  get diagnostics changed = row_count;
  d := d + changed;

  update public.dispatch_rounds
     set status = 'EXPIRED'
   where status = 'SENT'
     and deadline_at is not null and deadline_at <= p_at;
  get diagnostics changed = row_count;
  rr := rr + changed;

  update public.app_profiles
     set available_now = false
   where available_now = true
     and available_now_expires_at is not null
     and available_now_expires_at <= p_at;
  get diagnostics av = row_count;

  ur := private.expire_urgent(p_at);

  return jsonb_build_object(
    'needsExpired', ne,
    'responsesExpired', re,
    'notificationsExpired', nd,
    'schedulesDequeued', dq,
    'deliveriesExpired', d,
    'roundsExpired', rr,
    'availabilityExpired', av,
    'urgencyExpired', ur
  );
end;
$$;

revoke all on function private.expire_lifecycle(timestamptz)
  from public, anon, authenticated;

-- Repair Agreement cancellation for the same lifecycle-token regression while
-- preserving the already proven privacy, ghost-notification and replacement work.
create or replace function public.rpc_cancel_agreement(
  p_agreement_id uuid,
  p_reason text
) returns void language plpgsql security definer set search_path to 'pg_catalog' as $$
declare
  uid uuid := auth.uid();
  v_need_id uuid;
  v_agr public.agreements%rowtype;
  v_covered integer;
  v_need public.needs%rowtype;
begin
  if uid is null then raise exception 'AUTH_REQUIRED' using errcode = '28000'; end if;
  if coalesce(btrim(p_reason), '') = '' then
    raise exception 'REASON_REQUIRED' using errcode = 'P0001';
  end if;

  -- Discover without locking, authorize, then use the canonical lock order
  -- Need -> Agreement -> Response shared with selection/cancel/withdraw.
  select a.need_id into v_need_id
    from public.agreements a
   where a.id = p_agreement_id;
  if not found then raise exception 'AGREEMENT_NOT_FOUND' using errcode = 'P0002'; end if;
  if not public.fn_is_party(p_agreement_id, uid) then
    raise exception 'NOT_PARTY' using errcode = '42501';
  end if;

  select * into v_need
    from public.needs n
   where n.id = v_need_id
   for update;
  if not found then raise exception 'NEED_NOT_FOUND' using errcode = 'P0002'; end if;

  select * into v_agr from public.agreements
   where id = p_agreement_id for update;
  if not found then raise exception 'AGREEMENT_NOT_FOUND' using errcode = 'P0002'; end if;
  if v_agr.need_id is distinct from v_need.id then
    raise exception 'AGREEMENT_NEED_MISMATCH' using errcode = 'P0001';
  end if;
  if not public.fn_is_party(p_agreement_id, uid) then
    raise exception 'NOT_PARTY' using errcode = '42501';
  end if;
  if v_agr.status = 'CANCELLED' then return; end if;
  if v_agr.status = 'COMPLETED' then
    raise exception 'ALREADY_COMPLETED' using errcode = 'P0001';
  end if;

  update public.agreements set status = 'CANCELLED' where id = p_agreement_id;
  update public.agreement_execution set state = 'CANCELLED'
   where agreement_id = p_agreement_id;
  update public.need_selections set status = 'CANCELLED'
   where id = v_agr.selection_id;
  update public.marketplace_responses
     set status = 'NOT_SELECTED', selected_at = null
   where id = v_agr.selected_response_id;
  update public.access_grants
     set status = 'REVOKED',
         revoked_at = coalesce(revoked_at, statement_timestamp())
   where agreement_id = p_agreement_id and status = 'GRANTED';
  update public.notification_deliveries d
     set state = 'EXPIRED'
    from public.user_activity_events e
   where d.event_id = e.id
     and e.entity_type = 'AGREEMENT'
     and e.entity_id = p_agreement_id
     and d.state in ('CREATED','QUEUED','FAILED_RETRYABLE');

  v_covered := public.fn_need_covered_slots(v_agr.need_id);

  if v_covered < v_need.required_slots
     and v_need.status in ('ACTIVE','SELECTION') then
    perform set_config('uskoci.need_lifecycle', 'CANCEL_AGREEMENT', true);
    update public.needs set status = 'SELECTION' where id = v_need.id;
    perform private.enqueue_dispatch(v_need.id, statement_timestamp());
  end if;
end;
$$;

revoke all on function public.rpc_cancel_agreement(uuid,text)
  from public, anon, authenticated;
grant execute on function public.rpc_cancel_agreement(uuid,text) to authenticated;

comment on function public.rpc_cancel_agreement(uuid,text) is
  'M06 unilateral Agreement cancellation. Revokes grants, expires pending Agreement notifications, releases only its seat and explicitly wakes replacement dispatch. Lifecycle token repaired after guard_need_write.';
