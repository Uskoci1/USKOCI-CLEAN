-- Deleting an unpublished empty DRAFT and cancelling a lifecycle entity are
-- distinct product actions. Direct DELETE remains closed; this narrow path can
-- remove only a draft that has no marketplace/audit history and no storage
-- references. Sensitive draft-only construction data follows the Need FK.
create or replace function public.rpc_delete_draft_need(
  p_need_id uuid,
  p_need_revision integer,
  p_reason text default ''
) returns jsonb language plpgsql security definer set search_path to 'pg_catalog' as $$
declare
  u uuid := auth.uid();
  n public.needs;
begin
  if u is null then raise exception using errcode='42501', message='AUTH_REQUIRED'; end if;

  select * into n
    from public.needs x
   where x.id = p_need_id
   for update;

  if not found then
    if exists (
      select 1
        from private.marketplace_audit_log a
       where a.actor_user_id = u
         and a.event_type = 'NEED_DRAFT_DELETED'
         and a.entity_type = 'NEED'
         and a.entity_id = p_need_id
         and a.entity_version = p_need_revision
    ) then
      return jsonb_build_object(
        'needId', p_need_id,
        'revision', p_need_revision,
        'deleted', true,
        'idempotentReplay', true,
        'authoritative', true
      );
    end if;
    raise exception using errcode='P0002', message='NEED_NOT_FOUND';
  end if;

  if n.requester_account_id <> u then
    raise exception using errcode='42501', message='FORBIDDEN';
  end if;
  if n.revision is distinct from p_need_revision then
    raise exception using errcode='P0001', message='STALE_REVIEW_REQUIRED';
  end if;
  if n.status <> 'DRAFT' or n.published_at is not null then
    raise exception using errcode='22023', message='NEED_NOT_DELETABLE_DRAFT';
  end if;
  if cardinality(n.public_photo_paths) > 0 then
    raise exception using errcode='55000', message='DRAFT_MEDIA_CLEANUP_REQUIRED';
  end if;

  if exists (select 1 from public.marketplace_responses r where r.need_id = n.id)
     or exists (select 1 from public.need_selections s where s.need_id = n.id)
     or exists (select 1 from public.agreements a where a.need_id = n.id)
     or exists (select 1 from public.dispatch_rounds d where d.need_id = n.id)
     or exists (select 1 from public.opportunity_deliveries o where o.need_id = n.id)
     or exists (select 1 from private.dispatch_schedule q where q.need_id = n.id)
     or exists (
       select 1 from public.user_activity_events e
        where e.entity_type = 'NEED' and e.entity_id = n.id
     ) then
    raise exception using errcode='55000', message='DRAFT_HAS_AUTHORITATIVE_HISTORY';
  end if;

  delete from public.needs x where x.id = n.id;

  perform private.audit_marketplace(
    u,
    'NEED_DRAFT_DELETED',
    'NEED',
    n.id,
    n.revision,
    jsonb_build_object('reason', left(btrim(coalesce(p_reason, '')), 500))
  );

  return jsonb_build_object(
    'needId', n.id,
    'revision', n.revision,
    'deleted', true,
    'idempotentReplay', false,
    'authoritative', true
  );
end;
$$;

